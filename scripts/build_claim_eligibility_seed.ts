// Writes supabase/seed-data/facility_claim_eligibility.sql from the committed UUID map.
// Only reviewed, unique identities (status `mapped`) are eligible for claims. Unresolved identities are never written.
// Not a migration: the seed is loaded separately, after the migration, with an explicit approval.
// Run with: npx tsx scripts/build_claim_eligibility_seed.ts
import fs from 'node:fs';
import path from 'node:path';
import { parse } from './lib/facilityUuidMap';

const root = process.cwd();
const rows = parse(fs.readFileSync(path.join(root, 'data/facility-uuid-map.tsv'), 'utf8'));
const mapped = rows
  .flatMap((row) => (row.status === 'mapped' ? [row.uuid] : []))
  .sort();

const uniqueCount = new Set(mapped).size;
if (uniqueCount !== mapped.length) {
  throw new Error(`the map assigns one UUID to more than one identity (${mapped.length - uniqueCount} duplicates); refusing to write`);
}

const values = mapped.map((uuid) => `  ('${uuid}')`).join(',\n');
const sql = `-- Generated by scripts/build_claim_eligibility_seed.ts from data/facility-uuid-map.tsv.
-- ${mapped.length} reviewed, unique identities. Do not edit by hand. Load after the claim eligibility migration.
insert into public.facility_claim_eligibility (facility_id, source)
select v.id::uuid, 'facility-uuid-map'
from (values
${values}
) as v(id)
join public.facilities f on f.id = v.id::uuid
on conflict (facility_id) do nothing;
`;

const outDir = path.join(root, 'supabase/seed-data');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'facility_claim_eligibility.sql'), sql);
console.log(`Wrote ${mapped.length} eligible identities to supabase/seed-data/facility_claim_eligibility.sql`);
